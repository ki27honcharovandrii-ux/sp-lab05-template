#!/usr/bin/env bash
# ЗГЕНЕРОВАНО з content/sp/environment/lab05.yml — E11-9, ADR 022.
# Правки тут перезаписуються: змінювати треба environment-файл у матеріалах.
#
# Здача одним запуском: bash .devcontainer/submit.sh — або Ctrl+Shift+B.
#
# Здача в цьому курсі — це ТЕГ, а не пуш (ADR 020, submission_mode: "tag"). Звичайний
# `git push` зберігає роботу й НЕ здає її: автогрейдер прокидається на тег `submit/*`.
# Саме тому скрипт існує — щоб «я ж запушив» не означало «я не здав».
set -euo pipefail

LAB='lab05'

say()  { printf '%s\n' "$*"; }
die()  { printf '\n✗ %s\n' "$*" >&2; exit 1; }
# Свідома відмова студента — НЕ збій. З кодом 1 VS Code малює «terminated with exit
# code: 1», і людина, яка щойно сама відповіла «ні», читає це як поломку.
stop() { printf '\n%s\n' "$*"; exit 0; }

say "=== Здача ${LAB} ==="

git rev-parse --git-dir >/dev/null 2>&1 \
  || die "Це не репозиторій Git. Відкрий теку свого завдання."
git rev-parse HEAD >/dev/null 2>&1 \
  || die "У репозиторії немає жодного коміту — спершу збережи роботу."

# 1. Незбережене. Комітимо ТУТ, бо тег вішається на коміт: незбережений файл у здачу
#    не потрапить, і студент дізнається про це вже з нульової оцінки.
if [ -n "$(git status --porcelain)" ]; then
  say ""
  say "Незбережені зміни:"
  git status --short | sed 's/^/   /'
  say ""
  # `|| msg=""` — коли відповідати нікому (запуск без термінала), `read` упирається в
  # кінець вводу, і без цього `set -e` завалив би скрипт замість типового повідомлення.
  read -r -p "Повідомлення до коміту (Enter — «Робота над ${LAB}»): " msg || msg=""
  git add -A
  git commit -q -m "${msg:-Робота над ${LAB}}"
  say "✓ збережено"
fi

git push -q origin HEAD

# 2. Наступний ВІЛЬНИЙ суфікс, а не «останній + 1»: на живому суфікси не монотонні в
#    часі. Питаємо ВІДДАЛЕНИЙ репозиторій — зайнятість тега вирішує сервер, а локальні
#    теги бувають застарілі.
existing="$(git ls-remote --tags origin "refs/tags/submit/${LAB}*" 2>/dev/null \
  | awk '{print $2}')"
tag="submit/${LAB}"
n=1
while printf '%s\n' "$existing" | grep -qx "refs/tags/${tag}"; do
  n=$((n + 1)); tag="submit/${LAB}-${n}"
done

used=$(printf '%s\n' "$existing" | grep -c 'refs/tags/submit/' || true)
say ""
say "Буде створено тег: ${tag}"
say "Коміт:            $(git rev-parse --short HEAD) — $(git log -1 --pretty=%s)"
# НЕ «спроб»: ліміт спроб рахується інакше — червоні до першої зеленої його не їдять
# (HLD §4.3 п. 2). Число тегів, назване «спробами», виглядало б як лічильник ліміту,
# не будучи ним; це та сама брехня, що має вигляд факту.
[ "${used:-0}" -gt 0 ] && say "Здач у цьому репозиторії: ${used}"
say ""
# 3. Підтвердження — не формальність: спроб у курсі дві (HLD §4.3 п. 2), і здача в один
#    клік без питання зробила б зручним те, що коштує студентові спроби. Порожня
#    відповідь означає «ні»: мовчання не може означати згоду на таку дію.
read -r -p "Здаємо? [y/N] " ok || ok=""
case "$ok" in y|Y|т|Т) ;; *) stop "Скасовано. Нічого не здано." ;; esac

# `-f` тут не про перезапис здачі: ім'я вільне НА СЕРВЕРІ за побудовою вище. Воно
#  про локальний тег, який лишився від ручної здачі й нікуди не поїхав, — без `-f`
#  `git tag` упав би кодом 128 з англійським «already exists», і студент побачив би
#  збій замість здачі.
git tag -f "$tag" >/dev/null
git push -q origin "$tag"

repo="$(git config --get remote.origin.url | sed 's#.*github.com[:/]##; s#\.git$##')"
say ""
say "✓ Здано: ${tag}"
say ""
say "Що далі:"
say "  • автогрейдер запуститься сам, це кілька хвилин;"
say "  • результат — у Releases: https://github.com/${repo}/releases"
say "  • оцінка й коментар — у Feedback PR цього ж репозиторію."
